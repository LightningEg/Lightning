def strings(locale: str):
    """Return a fresh text map so rendering cannot mutate the shared translations."""
    return dict(_AR if locale == "ar" else _EN)


def error_text(message: str, locale: str) -> str:
    if locale == "ar":
        return _AR["generic_error"]
    return _ERRORS_EN.get(message, message or _EN["generic_error"])
