_DATE_WORDS = {**MONTHS, **FULL_MONTHS}
_MONTH_YEAR = re.compile(r"(" + "|".join(sorted(_DATE_WORDS, key=len, reverse=True)) + r")( \d{4})?")
_NUMERIC = {"n", "m", "x", "year", "amt", "amt2"}
_STAMPS = {"sa", "sb"}
_MONEY = r"[-+\u2212]?[\d.,]+[kM]?%?(?: [A-Z]{3})?"
_STAMP = r"\d{4}-\d\d(?:-\d\d)?"
_NUMBER = r"[-+\u2212]?[\d.,]+[kM]?%?"
_PATTERNS: list[tuple[tuple[str, ...], re.Pattern, str]] | None = None
_SEPARATORS = (" · ", " › ", " — ", ": ", ", ")
_SENTENCES = re.compile(r"(?<=[.؟?]) (?=[A-Z\u201c\"])")
_NAME_NUMBER = re.compile(r"(.+?) ([-+\u2212]?[\d.,]+[kM]?%?)")


def _patterns():
    """Every `{name}` entry, compiled once: its literal chunks (a cheap pre-check) and its regex."""
    global _PATTERNS
    if _PATTERNS is None:
        compiled = []
        for pattern, translated in ARABIC_UI.items():
            names = re.findall(r"\{([a-z_]+)\}", pattern)
            if not names:
                continue
            chunks = tuple(part for part in re.split(r"\{[a-z_]+\}", pattern) if part)
            seen: set[str] = set()
            pieces = []
            for part in re.split(r"(\{[a-z_]+\})", pattern):
                if re.fullmatch(r"\{[a-z_]+\}", part):
                    name = part[1:-1]
                    if name in seen:
                        pieces.append(f"(?P={name})")
                    else:
                        seen.add(name)
                        pieces.append(f"(?P<{name}>" + (_MONEY if name.startswith("amt") else _STAMP if name in _STAMPS else _NUMBER if name in _NUMERIC else ".+?") + ")")
                else:
                    pieces.append(re.escape(part))
            regex = "".join(pieces)
            compiled.append((chunks, re.compile(regex, re.S), translated))
        compiled.sort(key=lambda entry: -sum(len(chunk) for chunk in entry[0]))
        _PATTERNS = compiled
    return _PATTERNS


def chunks_text(chunks: tuple[str, ...]) -> str:
    return "".join(chunks)


def _translate_whole(value: str) -> str | None:
    if value in ARABIC_UI and "{" not in value:
        return ARABIC_UI[value]
    for chunks, regex, translated in _patterns():
        if all(chunk in value for chunk in chunks):
            match = regex.fullmatch(value)
            if match and " · " not in chunks_text(chunks) and any(" · " in v for v in match.groupdict().values()):
                continue  # a one-part pattern must not swallow a `A · B` line: each part is translated on its own
            if match:
                try:
                    return translated.format(**{k: _translate_text(v) for k, v in match.groupdict().items()})
                except (KeyError, IndexError):
                    continue
    return ARABIC_UI.get(value)


@lru_cache(maxsize=20000)
def _translate_text(value: str) -> str:
    """One whole string, else each part of a `A · B`, `A › B`, `A — B` or `A: B` line on its own."""
    whole = _translate_whole(value)
    if whole is not None:
        return whole
    month = _MONTH_YEAR.fullmatch(value)
    if month:
        return _DATE_WORDS[month.group(1)] + (month.group(2) or "")
    if value in WEEKDAYS:
        return WEEKDAYS[value]
    if value.endswith(".") and not value.endswith(".."):
        head = _translate_text(value[:-1])  # a name or list closing a sentence: "Transportation."
        if head != value[:-1]:
            return head + "."
    named = _NAME_NUMBER.fullmatch(value)
    if named:
        head = _translate_text(named.group(1))
        if head != named.group(1):
            return f"{head} {named.group(2)}"
    sentences = _SENTENCES.split(value)
    if len(sentences) > 1:
        done = [_translate_text(part) for part in sentences]
        if done != sentences:
            return " ".join(done)
    for separator in _SEPARATORS:
        if separator in value:
            done = [_translate_text(part) for part in value.split(separator)]
            if done == value.split(separator):
                return value
            return ("، " if separator == ", " else separator).join(done)  # the Arabic comma between list items
    return value


def translate(text: str, locale: str = "en", **values: object) -> str:
    value = str(text)
    if locale != "ar":
        return value.format(**values) if values else value
    if values:  # a system name passed in (an asset class, a category) is shown in Arabic; a typed name has no entry
        values = {k: _translate_text(v) if isinstance(v, str) else v for k, v in values.items()}
    if value in ARABIC_UI:
        translated = ARABIC_UI[value]
        return translated.format(**values) if values else translated
    return _translate_text(value.format(**values) if values else value)


_TAG = re.compile(r"(<script\b.*?</script>|<style\b.*?</style>|<textarea\b.*?</textarea>|<!--.*?-->|<[^>]+>|[^<]+)", re.S | re.I)
_ATTRIBUTE = re.compile(r"""(\s(?:title|aria-label|placeholder|alt|data-tip|data-busy|data-watch-label|data-confirm-delete|data-confirm|data-label)=)(["'])(.*?)\2""", re.S | re.I)
_LATIN = re.compile(r"[A-Za-z]{2}")


_ARROWS = str.maketrans("\u2192\u2190", "\u2190\u2192")


def _translate_piece(raw: str) -> str:
    plain = html.unescape(raw)
    if ("\u2192" in plain or "\u2190" in plain) and re.sub(r"\s+", " ", plain.strip()) not in ARABIC_UI:
        # A written arrow points the way the eye moves: on a right-to-left line, the other way (A06.2).
        raw = html.escape(plain.translate(_ARROWS), quote=False)
        plain = html.unescape(raw)
    if not _LATIN.search(plain):
        return raw
    stripped = re.sub(r"\s+", " ", plain.strip())
    translated = _translate_text(stripped)
    if translated == stripped:
        return raw
    lead, tail = plain[:len(plain) - len(plain.lstrip())], plain[len(plain.rstrip()):]
    return html.escape(lead + translated + tail, quote=True)


_DIGIT = "0-9\u0660-\u0669"
_DOT_AFTER_DIGIT = re.compile(rf"([{_DIGIT}%])\s*\u00b7\s*")
_DOT_BEFORE_DIGIT = re.compile(rf"\s*\u00b7\s*(?=[{_DIGIT}])")
_ENDS_WITH_DIGIT = re.compile(rf"[{_DIGIT}%]\s*$")
_STARTS_WITH_DIGIT = re.compile(rf"^\s*[{_DIGIT}]")
_LEADING_DOT = re.compile(r"^\s*\u00b7\s*")
_TRAILING_DOT = re.compile(r"\s*\u00b7\s*$")
_ARABIC_COMMA = "\u060c "


def arabic_dots(text: str) -> str:
    """A middle dot beside a number reads as the Arabic zero "\u0660" (Late \u00b7 17 days reads as 170): in Arabic the
    separator next to a digit is the Arabic comma. A dot between two words is left alone."""
    return _DOT_BEFORE_DIGIT.sub(_ARABIC_COMMA, _DOT_AFTER_DIGIT.sub(lambda m: m.group(1) + _ARABIC_COMMA, text))


def _dots_across_tags(out: list[str], kinds: list[str]) -> None:
    """The same rule when a tag sits between the dot and the number (`<time>2026-10-03</time> \u00b7 <span>Bill`)."""
    last = None
    for i, kind in enumerate(kinds):
        if kind == "barrier":  # a script, style, textarea or comment ends the run of visible text
            last = None
        elif kind == "text" and out[i].strip():
            if last is not None:
                if _ENDS_WITH_DIGIT.search(out[last]) and _LEADING_DOT.match(out[i]):
                    out[i] = _LEADING_DOT.sub(_ARABIC_COMMA, out[i], 1)
                elif _TRAILING_DOT.search(out[last]) and _STARTS_WITH_DIGIT.match(out[i]):
                    out[last] = _TRAILING_DOT.sub(_ARABIC_COMMA, out[last], 1)
            last = i


def localize_html(page: str) -> str:
    """The Arabic page's last pass: any visible text, title, aria-label or placeholder that a template or a Python
    sentence left in English is translated here from the same table. Data (names, refs, codes) has no entry, so it stays.
    A middle dot next to a number becomes the Arabic comma (`arabic_dots`)."""
    out, kinds = [], []

    def attribute(m):
        return m.group(1) + m.group(2) + arabic_dots(_translate_piece(m.group(3))) + m.group(2)

    for token in _TAG.findall(page):
        if token[:9].lower() == "<textarea":  # its typed text stays as typed; its placeholder is ours
            head, sep, rest = token.partition(">")
            out.append(_ATTRIBUTE.sub(attribute, head) + sep + rest)
            kinds.append("barrier")
        elif token.startswith("<"):
            plain_tag = token[:2] not in ("<!", "</") and token.lower()[:7] not in ("<script", "<style>", "<textar")
            if plain_tag:
                token = _ATTRIBUTE.sub(attribute, token)
            out.append(token)
            kinds.append("tag" if plain_tag or token[:2] == "</" else "barrier")
        else:
            out.append(arabic_dots(_translate_piece(token)))
            kinds.append("text")
    _dots_across_tags(out, kinds)
    return "".join(out)


def localized_figures(locale: str):
    """Keep shared figure names consistent across every template and report."""
    return {key: replace(figure, label=translate(figure.label, locale), meaning=translate(figure.meaning, locale))
            for key, figure in FIGURES.items()}


