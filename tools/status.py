def version() -> str:
    return re.search(r'__version__\s*=\s*"([^"]+)"', (ROOT / "lightning" / "__init__.py").read_text(encoding="utf-8")).group(1)


def items():
    milestones, problems = ISSUES.load()
    if problems:
        raise SystemExit("\n".join(problems))
    return [i for m in milestones for i in m["items"] if i["status"] != "parked"], milestones


def short(title: str, limit: int = 100) -> str:
    """The lead of a long title: up to its first " - ", at most `limit` characters."""
    title = title.split(" - ")[0]
    return title if len(title) <= limit else title[:limit - 1].rstrip() + "…"


def link(item, base: str) -> str:
    return f"[{short(item['title'])}]({base}issues/{item['file']})"


def _kind(item) -> str:
    return ISSUES.TAGS[item["tag"]].replace("improvement", "better").replace("new feature", "new")


def report_rows() -> list[tuple[str, str, list[str]]]:
    text = (ROOT / "issues" / "REPORTS.md").read_text(encoding="utf-8")
    rows = []
    for line in text.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        link_ = re.match(r"\[(.+?)\]\((.+?)\)", cells[1]) if len(cells) >= 5 else None
        if link_ and link_.group(2).endswith("report.md"):
            rows.append((link_.group(1), link_.group(2), [c.strip() for c in cells[4].split(",") if re.match(r"^\d+[A-Z]+$", c.strip())]))
    return rows


def ai_index() -> str:
    lines = ["# Map for AI sessions", "",
             "Generated by `python tools/status.py`; do not edit by hand. People read `docs/`; this folder and the files below "
             "hold the depth. Read sections, not files: grep the headings, then read that range, or use "
             "`python tools/status.py sections <file>`.", "",
             "| Read | What it holds |", "|---|---|"]
    lines += [f"| [{path}](../{path}) | {text} |" for path, text in AI_MAP]
    lines += ["", "Pillars (the shared categories) and sizes are defined in [issues/README.md](../issues/README.md)."]
    return "\n".join(lines) + "\n"


def sections(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    parts = re.split(r"(?m)^(?=## )", text)
    out = [f"{path.relative_to(ROOT).as_posix()}: {len(text.encode('utf-8')):,} bytes"]
    for part in parts:
        head = part.split("\n", 1)[0]
        out.append(f"  {len(part.encode('utf-8')):>8,}  {head if head.startswith('## ') else '(top)'}")
    return "\n".join(out)


def expected() -> dict[Path, str]:
    return {ROOT / "ai" / "INDEX.md": ai_index()}


def main() -> int:
    if sys.argv[1:2] == ["sections"]:
        print(sections(ROOT / sys.argv[2]))
        return 0
    stale = [path for path, text in expected().items() if not path.exists() or path.read_text(encoding="utf-8") != text]
    if "--check" in sys.argv:
        print("\n".join(f"{p.relative_to(ROOT).as_posix()} is out of date: run python tools/status.py" for p in stale) or "pages fine")
        return 1 if stale else 0
    for path, text in expected().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print(f"wrote {len(expected())} pages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
