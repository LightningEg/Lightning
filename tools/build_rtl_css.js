// Builds the Arabic stylesheets (style.rtl.css, phone.rtl.css, profiles.rtl.css) from the English ones: the same
// rules with every physical side swapped (rtlcss), served instead of the English file when the page is Arabic, so
// English is never touched. What is drawn rather than written stays as drawn (A12: charts do not mirror), and so do
// transforms, gradients and the few hand-written html[dir="rtl"] rules.
//   cd /tmp && npm i rtlcss postcss && NODE_PATH=/tmp/node_modules node <repo>/tools/build_rtl_css.js
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const postcss = require("postcss");
const rtlcss = require("rtlcss");

const STATIC = path.join(__dirname, "..", "lightning", "ui", "static");
const AS_DRAWN = /chart|spark|sankey|bullet|heat|donut|capital-marker|diverging|horizon-|plan-bar|flow-bar|stat-tile-visual|calendar|meter|zero-line|allocation-(track|fill)|compare-(track|current)|bridge-value|progress|treemap|pace-|kc-timeline|kc-columns|kc-dot/;
const KEEP_PROPS = new Set(["transform", "transform-origin", "cursor", "animation", "animation-name"]);

function rulesOf(root) {
  const out = [];
  root.walkRules((rule) => {
    if (rule.parent && rule.parent.type === "atrule" && /keyframes|font-face/.test(rule.parent.name)) return;
    out.push(rule);
  });
  return out;
}

function build(file, out) {
  const src = fs.readFileSync(path.join(STATIC, file), "utf8");
  const original = postcss.parse(src);
  const flipped = postcss.parse(rtlcss.process(src, { autoRename: false }));
  const a = rulesOf(original), b = rulesOf(flipped);
  if (a.length !== b.length) throw new Error(`${file}: rule count differs ${a.length} vs ${b.length}`);
  a.forEach((ra, i) => {
    const rb = b[i];
    const whole = ra.selector.includes("[dir=") || AS_DRAWN.test(ra.selector);
    const da = ra.nodes.filter((n) => n.type === "decl"), db = rb.nodes.filter((n) => n.type === "decl");
    if (da.length !== db.length) return;
    da.forEach((x, j) => {
      const y = db[j];
      if (whole || KEEP_PROPS.has(x.prop) || /gradient/.test(x.value)) {
        y.prop = x.prop;
        y.value = x.value;
        y.important = x.important;
      }
    });
  });
  const hash = crypto.createHash("sha256").update(src).digest("hex").slice(0, 16);
  fs.writeFileSync(path.join(STATIC, out), `/* ${out}: generated by tools/build_rtl_css.js from ${file} (source ${hash}); do not edit by hand. */\n` + flipped.toString());
  console.log(out, "from", file, hash);
}
build("style.css", "style.rtl.css");
build("phone.css", "phone.rtl.css");
build("profiles.css", "profiles.rtl.css");
