"""Check every report in report/ and rebuild its index.

    python tools/report_index.py            # rewrite report/INDEX.md
    python tools/report_index.py --check    # exit 1 if a report is malformed or INDEX.md is out of date

A report is report/<category>/<yyyy-mm-dd>-<area>-<what>.md and starts with a front matter block between two
`---` lines (see report/README.md for the fields). The index is the only file an AI reads before choosing a report.
"""
from __future__ import annotations

import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPORTS = ROOT / "report"
CATEGORIES = ("technical-bug", "visual-bug", "technical-improvement", "visual-improvement")
STATUSES = ("reported", "investigating", "open")
DONE = ("fixed", "declined", "not-reproduced")  # a processed report is deleted with its fix, never kept
REQUIRED = ("title", "category", "area", "status", "created", "reporter", "skills", "app_version", "commit", "repo")
MAX_REPORTS = 20  # more than this and nothing new is filed until some are processed
NAME = re.compile(r"^\d{4}-\d{2}-\d{2}-[a-z0-9]+(-[a-z0-9]+)+\.md$")


def front_matter(path: Path) -> dict[str, str]:
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        return {}
    data: dict[str, str] = {}
    for line in lines[1:]:
        if line.strip() == "---":
            return data
        key, sep, value = line.partition(":")
        if sep:
            data[key.strip()] = value.strip()
    return {}


def load() -> tuple[list[dict[str, str]], list[str]]:
    rows, problems = [], []
    for category in sorted(p for p in REPORTS.iterdir() if p.is_dir()):
        if category.name not in CATEGORIES:
            problems.append(f"report/{category.name}/ is not a category ({', '.join(CATEGORIES)})")
            continue
        for path in sorted(category.glob("*.md")):
            rel = f"{category.name}/{path.name}"
            meta = front_matter(path)
            if not meta:
                problems.append(f"{rel}: no front matter block")
                continue
            if not NAME.match(path.name):
                problems.append(f"{rel}: name must be yyyy-mm-dd-area-what.md in lower case with hyphens")
            for key in REQUIRED:
                if not meta.get(key):
                    problems.append(f"{rel}: front matter lacks '{key}'")
            if meta.get("category") != category.name:
                problems.append(f"{rel}: category '{meta.get('category')}' does not match its folder")
            if meta.get("status") in DONE:
                problems.append(f"{rel}: status '{meta['status']}' means it is processed: delete this file in the commit "
                                "that fixes or settles it (the test, changelog line and commit message are the record)")
            elif meta.get("status") not in STATUSES:
                problems.append(f"{rel}: status '{meta.get('status')}' is not one of {', '.join(STATUSES)}")
            if not re.search(r"^## Report\b", path.read_text(encoding="utf-8"), re.M):
                problems.append(f"{rel}: no '## Report' section")
            rows.append({**meta, "file": rel})
            try:
                date.fromisoformat(meta.get("created", ""))
            except ValueError:
                problems.append(f"{rel}: 'created' must be yyyy-mm-dd")
    if len(rows) > MAX_REPORTS:
        problems.append(f"{len(rows)} reports is over the limit of {MAX_REPORTS}: process some before filing more")
    return rows, problems


def render(rows: list[dict[str, str]]) -> str:
    order = {status: n for n, status in enumerate(STATUSES)}
    rows = sorted(rows, key=lambda r: (order.get(r.get("status", ""), 9), r["file"]))
    lines = [
        "# Report index",
        "",
        "Generated by `python tools/report_index.py`; do not edit by hand. Read this file, then open only the report you need.",
        "",
        f"{len(rows)} reports, all unprocessed. Status: reported (found, not looked at) · investigating · "
        "open (a real request, not built). A fixed report is deleted, so it is not listed. "
        f"Limits: {MAX_REPORTS} reports, past which the check fails; `tools/stale_check.py` lists any older than 30 days without an `issue:`.",
        "",
        "| Status | Category | Area | Title | Created | By | Report |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(f"| {r['status']} | {r['category']} | {r['area']} | {r['title']} | {r['created']} | {r['reporter']} | "
                     f"[{Path(r['file']).name}]({r['file']}) |")
    return "\n".join(lines) + "\n"


def main() -> int:
    rows, problems = load()
    text = render(rows)
    index = REPORTS / "INDEX.md"
    if "--check" in sys.argv:
        if not index.exists() or index.read_text(encoding="utf-8") != text:
            problems.append("report/INDEX.md is out of date: run python tools/report_index.py")
        print("\n".join(problems) or "reports fine")
        return 1 if problems else 0
    if problems:
        print("\n".join(problems))
        return 1
    index.write_text(text, encoding="utf-8")
    print(f"report/INDEX.md: {len(rows)} reports")
    return 0


if __name__ == "__main__":
    sys.exit(main())
